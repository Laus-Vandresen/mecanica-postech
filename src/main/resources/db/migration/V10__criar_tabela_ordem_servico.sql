CREATE TABLE ordem_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    veiculo_id BIGINT NOT NULL,
    orcamento_id BIGINT,
    data_abertura TIMESTAMP(6) NOT NULL,
    data_fechamento TIMESTAMP(6),
    status VARCHAR(30) NOT NULL,
    descricao VARCHAR(500),
    diagnostico VARCHAR(1000),
    valor_total NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_ordem_servico_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_ordem_servico_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo (id),
    CONSTRAINT fk_ordem_servico_orcamento FOREIGN KEY (orcamento_id) REFERENCES orcamento (id),
    CONSTRAINT uk_ordem_servico_orcamento UNIQUE (orcamento_id),
    CONSTRAINT ck_ordem_servico_status_nao_vazio CHECK (CHAR_LENGTH(TRIM(status)) > 0),
    CONSTRAINT ck_ordem_servico_valor_total_nao_negativo CHECK (valor_total >= 0),
    CONSTRAINT ck_ordem_servico_data_fechamento_valida CHECK (data_fechamento IS NULL OR data_fechamento >= data_abertura)
);

CREATE INDEX idx_ordem_servico_cliente_id ON ordem_servico (cliente_id);
CREATE INDEX idx_ordem_servico_veiculo_id ON ordem_servico (veiculo_id);
