CREATE TABLE veiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(8) NOT NULL,
    modelo VARCHAR(80) NOT NULL,
    marca VARCHAR(80),
    ano INTEGER,
    cliente_id BIGINT NOT NULL,
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT uk_veiculo_placa UNIQUE (placa),
    CONSTRAINT ck_veiculo_placa_nao_vazia CHECK (CHAR_LENGTH(TRIM(placa)) > 0),
    CONSTRAINT ck_veiculo_modelo_nao_vazio CHECK (CHAR_LENGTH(TRIM(modelo)) > 0),
    CONSTRAINT ck_veiculo_ano_positivo CHECK (ano IS NULL OR ano > 0)
);

CREATE INDEX idx_veiculo_cliente_id ON veiculo (cliente_id);
