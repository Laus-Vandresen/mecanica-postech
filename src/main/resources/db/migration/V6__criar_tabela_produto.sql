CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade_estoque INTEGER NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(255),
    CONSTRAINT ck_produto_nome_nao_vazio CHECK (CHAR_LENGTH(TRIM(nome)) > 0),
    CONSTRAINT ck_produto_valor_nao_negativo CHECK (valor >= 0),
    CONSTRAINT ck_produto_quantidade_estoque_nao_negativa CHECK (quantidade_estoque >= 0)
);
